import { afterAll, beforeAll, expect, test } from 'bun:test';
import { Database } from 'bun:sqlite';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { startTestServer } from './helpers/start-test-server';

let proc: any, base: string, dir: string, cookie: string;
beforeAll(async () => {
  dir = mkdtempSync(join(tmpdir(), 'usage-scope-'));
  ({proc, base} = await startTestServer(process.execPath, {cwd: join(import.meta.dir, '..'), env: {...process.env, DATA_DIR: dir, STYX_TEST_MODE: '1', JWT_SECRET: 'usage-test-jwt-secret-0123456789abcdef', API_KEY_SECRET: 'usage-test-key-secret-0123456789abcdef', INITIAL_PASSWORD: 'usage-test-password'}}));
  const login = await fetch(`${base}/api/auth/login`, {method:'POST', headers:{'content-type':'application/json'}, body:JSON.stringify({password:'usage-test-password'})});
  expect(login.status).toBe(200);
  cookie = (login.headers.get('set-cookie') || '').split(';')[0];
  const db = new Database(join(dir, 'storage.sqlite'));
  const now = new Date().toISOString();
  const historic = new Date(Date.now()-100*86400000).toISOString().slice(0,10);
  const insert = db.prepare(`INSERT INTO usage_history(timestamp,provider,model,account_key,account_label,api_key_id,api_key_name,tokens_input,tokens_output,success,latency_ms) VALUES (?,?,?,?,?,?,?,?,?,?,?)`);
  insert.run(now,'alpha','alpha-model','acct-a','Account A','key-a','Key A',10,20,0,100);
  insert.run(now,'beta','beta-model','acct-b','Account B','key-b','Key B',100,200,1,200);
  db.run(`INSERT INTO daily_usage_summary(date,provider,model,total_requests,total_input_tokens,total_output_tokens) VALUES (?, 'alpha','old-alpha',4,40,80), (?, 'beta','old-beta',8,400,800)`, [historic,historic]);
  db.run(`INSERT INTO call_logs(id,timestamp,provider,model,requested_model,status,error_type,api_key_id,api_key_name) VALUES ('a',?,'alpha','alpha-model','different',500,'alpha-error','key-a','Key A'),('b',?,'beta','beta-model','beta-model',429,'beta-error','key-b','Key B')`, [now,now]);
  db.run("UPDATE key_value SET value = '30' WHERE namespace = 'databaseSettings' AND key = 'usageHistory'");
  db.close();
});
afterAll(() => { proc?.kill('SIGKILL'); if(dir) rmSync(dir,{recursive:true,force:true}); });

test('populated provider analytics scopes raw, history, account, key and errors and requires management auth', async () => {
  const path = '/api/usage/analytics?range=all&provider=ALPHA&presets=all,30d';
  expect((await fetch(base+path)).status).toBe(401);
  const response = await fetch(base+path,{headers:{cookie}});
  expect(response.status).toBe(200);
  const j: any = await response.json();
  expect(j.summary.totalRequests).toBe(5);
  expect(j.summary.totalTokens).toBe(150);
  expect(j.dailyTrend.reduce((sum: number, day: any) => sum + day.requests, 0)).toBe(5);
  expect(j.dailyTrend.reduce((sum: number, day: any) => sum + day.totalTokens, 0)).toBe(150);
  expect(j.dailyByModel.every((day: any) => !('beta-model' in day) && !('old-beta' in day))).toBe(true);
  expect(j.summary.fallbackCount).toBe(1);
  expect(j.byProvider.map((p: any)=>p.providerId)).toEqual(['alpha']);
  expect(j.byModel.map((m: any)=>m.model).sort()).toEqual(['alpha-model','old-alpha']);
  expect(j.byAccount.map((a: any)=>a.account)).toEqual(['Account A']);
  expect(j.byApiKey.map((k: any)=>k.apiKeyName)).toEqual(['Key A']);
  expect(j.byAccount[0].requests).toBe(1);
  expect(j.byApiKey[0].requests).toBe(1);
  expect(j.accountAndApiKeySource).toBe('retained_raw_usage_history');
  expect(j.activityMapSource).toBe('retained_raw_usage_history');
  expect(j.activityMap[new Date(Date.now()-100*86400000).toISOString().slice(0,10)]).toBeUndefined();
  expect(j.errorBreakdown).toEqual([{errorType:'alpha-error',count:1}]);
  const filtered = await fetch(base+'/api/usage/analytics?range=all&provider=alpha&apiKeyIds=key-a',{headers:{cookie}});
  expect(filtered.status).toBe(200);
  const f: any = await filtered.json();
  expect(f.summary.totalRequests).toBe(1);
  expect(f.summary.totalTokens).toBe(30);
  expect(f.byApiKey.map((k: any)=>k.apiKeyName)).toEqual(['Key A']);
  const injected = await fetch(base+'/api/usage/analytics?range=all&provider='+encodeURIComponent("alpha' OR 1=1 --"),{headers:{cookie}});
  expect(injected.status).toBe(200);
  const i: any = await injected.json();
  expect(i.summary.totalRequests).toBe(0);
  expect(i.byProvider).toEqual([]);
});
